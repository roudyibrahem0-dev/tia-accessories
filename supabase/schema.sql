create policy "Authenticated users can upload store images" on storage.objects for insert to authenticated with check (bucket_id in ('product-images', 'category-images'));
create policy "Authenticated users can update store images" on storage.objects for update to authenticated using (bucket_id in ('product-images', 'category-images'));
create policy "Authenticated users can delete store images" on storage.objects for delete to authenticated using (bucket_id in ('product-images', 'category-images'));
