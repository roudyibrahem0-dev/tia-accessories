create extension if not exists "pgcrypto";

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric(12,2) not null default 0,
  cost numeric(12,2) default 0,
  description text,
  category text,
  material text,
  color_finish text,
  care_instructions text,
  warranty_text text default 'مقاوم للصدأ ولا يتغير لونه مع الماء',
  image_url text,
  gallery_images jsonb default '[]'::jsonb,
  video_url text,
  stock_qty integer default 0,
  discount_type text default 'percent' check (discount_type in ('percent', 'fixed')),
  discount_value numeric default 0,
  discount_active boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  title text not null,
  count text,
  image text,
  quote text,
  author text,
  created_at timestamptz not null default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null unique,
  email text,
  address text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number bigint generated by default as identity unique,
  customer_id bigint references public.customers(id) on delete set null,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  customer_location text,
  total_price numeric(12,2) not null default 0,
  subtotal numeric(12,2) not null default 0,
  status text not null default 'pending',
  order_source text default 'other',
  items jsonb not null default '[]'::jsonb,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text,
  discount_type text not null default 'percent' check (discount_type in ('percent', 'fixed')),
  discount_value numeric(12,2) not null default 0,
  min_order numeric(12,2) default 0,
  active boolean not null default true,
  used_count integer not null default 0,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.product_reviews (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  customer_name text not null default 'زبون',
  rating integer not null check (rating between 1 and 5),
  comment text not null,
  image_urls jsonb default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.general_inventory (
  id bigint generated by default as identity primary key,
  name text not null,
  material text,
  quantity numeric not null default 0,
  price numeric(12,2) not null default 0,
  unit text,
  low_stock_threshold numeric default 0,
  low_stock_alerted boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_activity_log (
  id bigint generated by default as identity primary key,
  action text not null,
  details text,
  created_at timestamptz not null default now()
);

create table if not exists public.monthly_archives (
  id bigint generated by default as identity primary key,
  month_year text not null unique,
  total_sales numeric(12,2) not null default 0,
  orders_count integer not null default 0,
  created_at timestamptz not null default now()
);

